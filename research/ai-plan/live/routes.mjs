/**
 * routes.mjs — offline route construction for P7's live experiments.
 *
 * Separated from kit.mjs so the kit stays a pure tool library. Every belt cell is
 * solved with src/ai/belt-rules.mjs (solveTurn / beltCode) — never proto/belt-rules.mjs,
 * whose beltEntry is wrong for curved belts (redteam #1(2)).
 *
 * Site rule: a hub-delivery line ALWAYS touches the hub, and in a fresh save the hub
 * sits at the origin — so the ">150 cells from origin" discipline cannot apply to the
 * T1/T2/T3 delivery lines. What protects the world there is: isolated new save +
 * snapshot + obs-verified-empty landing box, never the level-11 save. The 150-cell rule
 * is enforced for the non-delivery experiments (F1/F2) via findClearSite().
 */
import { beltPart, minerPart, hubEntries, offlineTile, OPP } from "./kit.mjs";

export const FLOW = { 0: "top", 90: "right", 180: "bottom", 270: "left" };

/**
 * L route: miner (standing on a resource cell) ejects "top", runs a vertical leg up to
 * a corner at the entry row, then a horizontal leg into a hub side entry.
 * The corner is generated by solveTurn and carried explicitly in the blueprint (never
 * left to the game's neighbour-derived auto-orientation).
 */
export function lRoute(miner, entry) {
    const [mx, my] = miner;
    const [ex, ey] = entry;
    if (ey >= my) throw new Error(`corner would not be above the miner: miner=${miner} entry=${entry}`);
    const hdir = ex > mx ? "right" : "left";
    if (mx === ex) throw new Error(`degenerate column: miner=${miner} entry=${entry}`);

    const parts = [];
    parts.push(minerPart(miner, "top")); // miner ejector is local top (buildings/miner.js:82-84)
    for (let y = my - 1; y > ey; y--) parts.push(beltPart([mx, y], "bottom", "top"));
    parts.push(beltPart([mx, ey], "bottom", hdir)); // the corner
    const step = hdir === "right" ? 1 : -1;
    for (let x = mx + step; step > 0 ? x <= ex : x >= ex; x += step) parts.push(beltPart([x, ey], OPP[hdir], hdir));

    const last = parts[parts.length - 1].cell;
    if (last[0] !== ex || last[1] !== ey) throw new Error(`route tail ${JSON.stringify(last)} != entry ${JSON.stringify(entry)}`);
    return parts;
}

/** straight run of belts from `from` to `to` inclusive, all flowing `dir`. */
export function straightRun(from, to, dir) {
    const parts = [];
    const [ddx, ddy] = { top: [0, -1], right: [1, 0], bottom: [0, 1], left: [-1, 0] }[dir];
    const n = ddx !== 0 ? Math.abs(to[0] - from[0]) : Math.abs(to[1] - from[1]);
    for (let i = 0; i <= n; i++) parts.push(beltPart([from[0] + ddx * i, from[1] + ddy * i], OPP[dir], dir));
    return parts;
}

/** resource cells of `shape` within `range` of the hub centre, nearest first. */
export function findResourceCells(seed, shape, hub, range = 48) {
    const ccx = hub.x + 1.5, ccy = hub.y + 1.5;
    const hits = [];
    for (let x = Math.floor(ccx) - range; x <= Math.ceil(ccx) + range; x++) {
        for (let y = Math.floor(ccy) - range; y <= Math.ceil(ccy) + range; y++) {
            if (offlineTile(seed, x, y) !== shape) continue;
            if (x >= hub.x - 1 && x <= hub.x + 4 && y >= hub.y - 1 && y <= hub.y + 4) continue;
            hits.push([x, y]);
        }
    }
    hits.sort((a, b) => Math.hypot(a[0] - ccx, a[1] - ccy) - Math.hypot(b[0] - ccx, b[1] - ccy));
    return hits;
}

/**
 * Feasible L routes to a left/right hub column entry, shortest first.
 * opts: {range, minBelts, maxBelts, side}
 */
export function planLRoutes(seed, shape, hub, opts = {}) {
    const range = opts.range || 48;
    const minBelts = opts.minBelts || 2;
    const maxBelts = opts.maxBelts || 40;
    const cells = findResourceCells(seed, shape, hub, range);
    const entries = hubEntries(hub).filter(
        (e) => (opts.side ? e.side === opts.side : e.side === "left" || e.side === "right")
    );
    const out = [];
    let lastError = null;
    for (const m of cells) {
        for (const ent of entries) {
            const [ex, ey] = ent.at;
            if (ey >= m[1]) continue; // corner must sit above the miner
            if (ent.side === "left" && !(m[0] < ex)) continue;
            if (ent.side === "right" && !(m[0] > ex)) continue;
            const belts = m[1] - ey + Math.abs(ex - m[0]); // (my-ey-1) vertical + corner + horizontal leg
            if (belts < minBelts || belts > maxBelts) continue;
            try {
                const parts = lRoute(m, ent.at);
                const corners = parts.filter((p) => p.kind === "belt" && p.corner);
                out.push({ miner: m, entry: ent, parts, belts, corners });
            } catch (e) {
                lastError = e.message; // never swallow silently: a rejected route must be explainable
            }
        }
    }
    out.sort((a, b) => a.belts - b.belts);
    return out;
}

/**
 * A detached belt line for the forensic experiments (F1/F2): w cells long, placed so its
 * bbox centre is at least `minDist` from the origin. Returns cells only, hub-free.
 */
export function detachedLine(anchor, len, dir) {
    const [ddx, ddy] = { top: [0, -1], right: [1, 0], bottom: [0, 1], left: [-1, 0] }[dir];
    const cells = [];
    for (let i = 0; i < len; i++) cells.push([anchor[0] + ddx * i, anchor[1] + ddy * i]);
    return cells;
}
